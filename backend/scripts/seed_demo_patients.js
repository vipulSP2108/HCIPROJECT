async function seedDemoPatients() {
  try {
    console.log("Connecting to MongoDB:", process.env.MONGODB_URI ? "URI provided" : "NO URI!");
    await mongoose.connect(process.env.MONGODB_URI, {
      useNewUrlParser: true,
      useUnifiedTopology: true,
    });
    console.log("MongoDB Connected Successfully");

    for (const patientData of DEMO_PATIENTS) {
      console.log(`\n========================================`);
      console.log(`Seeding Demo Patient: ${patientData.name} (${patientData.email})`);

      // 1. Upsert User
      let user = await User.findOne({ email: patientData.email });
      if (!user) {
        user = await User.create({
          name: patientData.name,
          email: patientData.email,
          password: patientData.password,
          phone: patientData.phone,
          type: patientData.type,
          patientDetails: patientData.patientDetails,
        });
        console.log(`✓ Created User: ${user._id}`);
      } else {
        user.name = patientData.name;
        user.phone = patientData.phone;
        user.patientDetails = patientData.patientDetails;
        await user.save();
        console.log(`✓ Updated User: ${user._id}`);
      }

      // 2. Clear old demo sessions for this user to ensure pristine state
      await AssessmentSession.deleteMany({ user: user._id });
      await ClinicalTestSession.deleteMany({ user: user._id });

      // 3. Create Multi-Session Records
      for (const s of patientData.sessions) {
        const sessionDate = new Date(Date.now() - s.daysAgo * 86400 * 1000);

        // A. Create ClinicalTestSession
        const clinicalSession = await ClinicalTestSession.create({
          user: user._id,
          phase: s.phase,
          activeArm: patientData.activeArm,
          createdAt: sessionDate,
          completedAt: sessionDate,
          test1_grossReach: s.test1_grossReach,
          test2_objectTransfer: s.test2_objectTransfer,
          test3_pinch: s.test3_pinch,
          test4_reactionStrike: s.test4_reactionStrike,
          test5_romSweep: s.test5_romSweep,
        });

        // B. Compute Clinical Metrics & Overall Composite Score
        const clinicalMetrics = computeClinicalMetrics(clinicalSession);

        // C. Create AssessmentSession
        const assessment = await AssessmentSession.create({
          user: user._id,
          phase: s.phase,
          track: "clinical",
          label: s.label,
          status: "completed",
          createdAt: sessionDate,
          completedAt: sessionDate,
          clinicalTestSessionId: clinicalSession._id,
          clinicalMetrics,
          overallScore: clinicalMetrics.clinical_overallScore || 75,
          overallUncappedScore: clinicalMetrics.clinical_uncappedScore || 85,
        });

        // D. Save JSON and CSV Matrix Files user-wise on disk
        const savedFiles = await saveUserMatrixFiles({
          user,
          assessment,
          clinicalSession,
        });

        console.log(`  ✓ Session "${s.label}" (${s.phase}) saved. Score: ${assessment.overallScore} pts.`);
        console.log(`    Matrix JSON: ${savedFiles.jsonFilename}`);
        console.log(`    Matrix CSV:  ${savedFiles.csvFilename}`);
      }
    }

    console.log(`\n========================================`);
    console.log(`✓ All 5 Demo Patients Seeded Successfully with user-wise files!`);
    process.exit(0);
  } catch (err) {
    console.error("Seeding Error:", err);
    process.exit(1);
  }
}

seedDemoPatients();

